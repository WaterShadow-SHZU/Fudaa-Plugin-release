def unescape(text):
    return re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: chr(int(m.group(1), 16)), text)


def escape(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 32 or ord(ch) > 126:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


def plain_english(value):
    return unescape(value).replace("_", " ").strip()


def translate(english):
    return EXACT.get(plain_english(english).lower())


def convert(raw):
    lines = []
    seen = set()
    for line in raw.splitlines():
        if "=" not in line or line.startswith("#"):
            continue
        key, en = line.split("=", 1)
        zh = translate(en)
        if not zh:
            continue
        stored = escape(unescape(key)) + "=" + escape(zh)
        if stored not in seen:
            lines.append(stored)
            seen.add(stored)
    for key, zh in DIRECT.items():
        stored = escape(key.replace(" ", "_")) + "=" + escape(zh)
        if stored not in seen:
            lines.append(stored)
            seen.add(stored)
    if not lines:
        return "\n"
    return "\n".join(lines) + "\n"


